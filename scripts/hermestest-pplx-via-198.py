#!/usr/bin/env python3
"""hermestest-pplx-via-198.py — 让一个 hermestest 实例的 web_search 走 198（和 carher-14 一样）。

为什么需要它（2026-10-23）
--------------------------
OpenClaw perplexity 插件只有在 ``plugins.entries.perplexity.config.webSearch`` 写明
``{apiKey, baseUrl, model}`` 时才走 198。这块空着（``{}``）时插件**静默回落容器里的
``OPENROUTER_API_KEY`` 直连 OpenRouter**，198 上的 per-key alias 对它完全不起作用。
10-23 OpenRouter 整号下线 ⇒ hermestest-13/75 搜索全 ``401 User not found``，
而 198 映射早就配好了。补上这块后两台立刻恢复（同题答对、25~29 条引用）。

做了什么（每步都断言，失败即停）
--------------------------------
1. 按容器的 bind mount 找宿主 ``openclaw.runtime.json5``（13 在 186、75/14 在 188，别猜路径）。
2. 文件里已有 ``webSearch`` ⇒ 只报现状不写（幂等）。
3. ``cp -p`` 备份 ``<file>.bak-pplx-via-198-<ts>``。
4. 在唯一的 ``    entries: {`` 锚点后插入 perplexity 块；**原地覆写保 inode**
   （单文件 bind mount，``sed -i`` 换 inode 容器看不到，见 skill hermestest-web-search-provider §3）。
5. 等 gateway 打 ``config hot reload applied``。
6. ``infer web search`` 实打一题，断言 ``provider=perplexity`` + 有引用。
7. **``docker restart``**（``--no-restart`` 可跳过）：只热重载的话 OpenClaw 2026.8.1 之后每条飞书消息都报
   ``PreparedModelCatalogConfigReplacedError`` 不回复（10-23 13/75 实测）。重启后等 ``ws client ready``，
   断言 ``PreparedModelCatalog`` 计数为 0。会断约 1 分钟，先跟用户说。

model 名必须在这把 key 的 198 白名单里：13/75 只有 ``perplexity-sonar``，14 另有 ``-search``。
脚本不替你判白名单——``--model`` 默认 ``perplexity-sonar``，L2 报 403 就是不在白名单。

🔴 文件头是 ``// AUTOGENERATED DO NOT EDIT.``，redeploy 会冲掉，冲掉后零症状回落 OpenRouter。
长期要改生成器（``/Data/carher-runtime-orchestra/deploy/bots/carher-<N>.s3.json``），本脚本不管。

用法（Mac 上跑，经 jms）::

    scripts/hermestest-pplx-via-198.py --asset JSZX-AI-03 --instance hermestest-75            # dry-run
    scripts/hermestest-pplx-via-198.py --asset JSZX-AI-01 --instance hermestest-13 --apply
    scripts/hermestest-pplx-via-198.py --self-test                                           # 离线测插入逻辑
    # 回滚：在该机上 cat <备份> > <文件>（同样保 inode），等热重载

退出码：0 成功/已是目标状态  1 校验失败  2 参数/定位失败  4 jms 调用失败
"""
from __future__ import annotations

import argparse
import base64
import os
import shlex
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
JMS = os.path.join(HERE, "jms")
ANCHOR = "    entries: {\n"


def insert_block(text: str, model: str) -> str:
    """在唯一的 ``entries: {`` 锚点后插入 perplexity.webSearch 块。远端和 --self-test 共用这一份。"""
    n = text.count(ANCHOR)
    if n != 1:
        raise SystemExit(f"STOP: 锚点 'entries: {{' 出现 {n} 次（要恰好 1 次）")
    if "webSearch" in text:
        raise SystemExit("STOP: 已有 webSearch")
    block = (
        "      // @pplx-via-litellm · web_search 经 198（perplexity 名 → per-key alias → grok multi-agent），同 carher-14。\n"
        "      // 不配这块插件会回落容器 OPENROUTER_API_KEY 直连 OpenRouter。由 scripts/hermestest-pplx-via-198.py 写入。\n"
        "      perplexity: {\n"
        "        enabled: true,\n"
        "        config: {\n"
        "          webSearch: {\n"
        '            apiKey: "${CARHER_PROD_KEY}",\n'
        '            baseUrl: "https://cc.auto-link.com.cn/pro/v1",\n'
        f'            model: "{model}",\n'
        "          },\n"
        "        },\n"
        "      },\n"
    )
    new = text.replace(ANCHOR, ANCHOR + block, 1)
    assert len(new) - len(text) == len(block)
    return new


# 远端 python：把 insert_block 的源码原样带过去，避免两份逻辑漂移
REMOTE_PY = f"""
import sys
ANCHOR = {ANCHOR!r}
""" + __import__("inspect").getsource(insert_block) + """
p, model, out = sys.argv[1], sys.argv[2], sys.argv[3]
open(out, "w").write(insert_block(open(p).read(), model))
"""

REMOTE_SH = r'''
set -eu
F=$(docker inspect "$C" --format '{{range .Mounts}}{{if eq .Destination "/data/.openclaw/openclaw.json"}}{{.Source}}{{end}}{{end}}' 2>/dev/null || true)
if [ -z "$F" ] || [ ! -f "$F" ]; then echo "STOP: 找不到 $C 的 openclaw.json 宿主文件（容器不在这台？13 在 186，14/75 在 188）"; exit 2; fi
echo "file=$F"
X="docker exec -e HOME=/data $C"
CUR=$($X openclaw config get plugins.entries.perplexity.config 2>&1 | grep -v -E '^\[config\] warnings|^⚠' || true)
if grep -q webSearch "$F"; then echo "ALREADY: 文件里已有 webSearch，不写。当前生效值："; printf '%s\n' "$CUR"; exit 0; fi
echo "current perplexity.config: $(printf '%s' "$CUR" | tr -d '\n ')"
T=$(mktemp -d)
printf '%s' "$PYB64" | base64 -d > "$T/ins.py"
python3 "$T/ins.py" "$F" "$MODEL" "$T/new"
if [ "$APPLY" != 1 ]; then echo "DRY-RUN: 会在 entries 首项插入 perplexity.webSearch(model=$MODEL)，加 --apply 才写"; diff "$F" "$T/new" | head -20 || true; rm -rf "$T"; exit 0; fi
if ! docker exec "$C" printenv CARHER_PROD_KEY >/dev/null 2>&1; then echo "STOP: 容器里没有 CARHER_PROD_KEY，插值会抛 MissingEnvVarError"; rm -rf "$T"; exit 1; fi
B="$F.bak-pplx-via-198-$(date +%Y%m%dT%H%M%S)"
cp -p "$F" "$B"
I0=$(stat -c %i "$F")
cat "$T/new" > "$F"; rm -rf "$T"
I1=$(stat -c %i "$F")
echo "backup=$B"
if [ "$I0" != "$I1" ]; then echo "STOP: inode 变了 $I0→$I1，容器看不到新文件；docker restart $C 或回滚"; exit 1; fi
R=""
for i in $(seq 1 24); do
  sleep 5
  R=$(docker logs --since 3m "$C" 2>&1 | grep -E "config hot reload applied|config reload skipped" | tail -1 || true)
  [ -n "$R" ] && break
done
echo "reload: ${R:-（120s 内没看到 reload 行）}" | cut -c1-200
case "$R" in *"hot reload applied"*) ;; *) echo "STOP: 没热重载成功，回滚：cat $B > $F"; exit 1;; esac
S=$(date +%s)
O=$($X timeout 120 openclaw infer web search --query "$QUERY" 2>&1 | grep -v -E '^\[config\] warnings|^⚠' || true)
TOOK=$(( $(date +%s) - S ))
if printf '%s' "$O" | grep -q '^{"result"'; then
  printf '%s' "$O" | grep '^{"result"' | tail -1 | TOOK=$TOOK python3 -c '
import sys, json, os
r = json.load(sys.stdin)["result"]; c = len(r.get("citations") or [])
print("L2 provider=%s model=%s citations=%d took=%ss" % (r.get("provider"), r.get("model"), c, os.environ["TOOK"]))
print("   ", (r.get("content") or "")[60:180].replace("\n", " "))
sys.exit(0 if r.get("provider") == "perplexity" and c > 0 else 1)'
else
  echo "L2 FAIL: $(printf '%s' "$O" | tail -c 250)"
  echo "  ⇒ 有 req: xxxxxxxx 就去 198 查原文（cli-anything-litellm db req <id>）；403 多半是 model 不在这把 key 的白名单"
  exit 1
fi
if [ "$RESTART" != 1 ]; then echo "⚠️ 没重启：热重载后回复路径可能坏（PreparedModelCatalogConfigReplacedError），尽快 docker restart $C"; exit 0; fi
T0=$(date -u +%Y-%m-%dT%H:%M:%SZ)
docker restart "$C" >/dev/null
for i in $(seq 1 40); do docker logs --since "$T0" "$C" 2>&1 | grep -q 'ws client ready' && break; sleep 5; done
N=$(docker logs --since "$T0" "$C" 2>&1 | grep -c PreparedModelCatalog || true)
echo "restart: ws_ready=$(docker logs --since "$T0" "$C" 2>&1 | grep -c 'ws client ready') catalog_errors=$N"
[ "$N" = 0 ] || { echo 'STOP: 重启后仍报 PreparedModelCatalog'; exit 1; }
'''


def self_test() -> int:
    base = "  plugins: {\n    entries: {\n      \"acpx\": { enabled: true },\n    },\n  },\n"
    out = insert_block(base, "perplexity-sonar")
    assert out.count("webSearch") == 1 and 'model: "perplexity-sonar"' in out
    assert out.index("perplexity: {") < out.index('"acpx"')          # 插在 entries 首项
    assert out.replace(out[out.index(ANCHOR) + len(ANCHOR):out.index('      "acpx"')], "") == base
    for bad, why in ((base + base, "两个锚点"), ("x\n", "没有锚点"), (out, "已有 webSearch")):
        try:
            insert_block(bad, "m")
        except SystemExit:
            continue
        raise AssertionError(f"{why} 应该 STOP")
    # 远端那段 python 能单独跑（防源码搬运出错）
    compile(REMOTE_PY, "<remote>", "exec")
    print("self-test OK")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--asset", help="jms 资产名：JSZX-AI-01(186) / JSZX-AI-03(188)")
    ap.add_argument("--instance", help="容器名，如 hermestest-75")
    ap.add_argument("--model", default="perplexity-sonar",
                    help="198 上的组名，必须在这把 key 的白名单里（13/75 只有 perplexity-sonar）")
    ap.add_argument("--query", default="2026年10月20日恒生指数收盘多少点",
                    help="必须是训练截止后的事实，否则没搜也能答对")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--no-restart", action="store_true",
                    help="只热重载不重启（不推荐：13/75 实测热重载后不回复）")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    if not (a.asset and a.instance):
        ap.error("--asset 和 --instance 必填")
    if not os.access(JMS, os.X_OK):
        print(f"[FATAL] 找不到可执行的 {JMS}", file=sys.stderr)
        return 2
    env = "".join(f"{k}={shlex.quote(v)}\n" for k, v in (
        ("C", a.instance), ("APPLY", "1" if a.apply else "0"), ("MODEL", a.model), ("QUERY", a.query),
        ("RESTART", "0" if a.no_restart else "1"),
        ("PYB64", base64.b64encode(REMOTE_PY.encode()).decode())))
    p = subprocess.run([JMS, "ssh", a.asset, "bash -s"], input=env + REMOTE_SH, text=True)
    return 4 if p.returncode == 255 else p.returncode


if __name__ == "__main__":
    sys.exit(main())

def js(fn, *args):
    code = (f"const m=require({json.dumps(str(SRC / 'carher_models_sync.js'))});"
            f"process.stdout.write(JSON.stringify(m.{fn}(...{json.dumps(list(args))})))")
    return json.loads(subprocess.run(["node", "-e", code], capture_output=True, text=True, check=True).stdout)


@pytest.mark.parametrize("text", [
    CFG,
    CFG.replace(OLD, OLD + "/"),                                      # 末尾带斜杠也算
    CFG.replace(f'openai_base_url = "{OLD}"\n', ""),                  # 只有 provider 那行
    CFG.replace(OLD, "https://chat.auto-link.com.cn/model/v1"),        # 已经是新地址 ⇒ 不动
    CFG.replace(OLD, "https://cc.auto-link.com.cn/pro/v1beta"),        # 形状不同 ⇒ 不动
])
def test_migrate_base_urls_identical_and_scoped(text):
    new = "https://chat.auto-link.com.cn/model/v1"
    got_py, got_js = py.migrate_base_urls(text, new), js("migrateBaseUrls", text, new)
    assert got_py == got_js
    if "cc.auto-link.com.cn/pro/v1\"" in text or "cc.auto-link.com.cn/pro/v1/\"" in text:
        assert got_py is not None and "cc.auto-link.com.cn" not in got_py
        # 除了地址那几行,逐行不变
        a, b = text.splitlines(), got_py.splitlines()
        assert len(a) == len(b)
        diff = [(x, y) for x, y in zip(a, b) if x != y]
        assert diff and all("base_url" in x and y.endswith(f'"{new}"') for x, y in diff), diff
        assert 'base_url = "https://api.example.com/v1"' in got_py, "用户自己的 provider 被动了"
    else:
        assert got_py is None


class _GW(http.server.BaseHTTPRequestHandler):
    hits = []

    def log_message(self, *a):
        pass

    def do_GET(self):
        _GW.hits.append(self.path)
        ok = self.headers.get("Authorization") == f"Bearer {KEY}"
        body = {"data": [{"id": "gpt-5.6-terra"}, {"id": "grok-4.7"}]} if ok else {"error": "no"}
        if ok and self.path.endswith("/model/info"):
            body = {"data": []}
        b = json.dumps(body).encode()
        self.send_response(200 if ok else 401)
        self.send_header("content-type", "application/json")
        self.end_headers()
        self.wfile.write(b)


@pytest.fixture(scope="module")
def gw():
    s = http.server.ThreadingHTTPServer(("127.0.0.1", 0), _GW)
    threading.Thread(target=s.serve_forever, daemon=True).start()
    yield f"http://127.0.0.1:{s.server_port}/model/v1"
    s.shutdown()


def _home(tmp_path, cfg=CFG, key=KEY):
    ch = tmp_path / ".codex"
    ch.mkdir(parents=True)
    (ch / "config.toml").write_text(cfg)
    (ch / "auth.json").write_text(json.dumps({"auth_mode": "apikey", "OPENAI_API_KEY": key}))
    # 现有目录当模板(没有 codex 时 loadTemplates 退回它)
    (ch / "carher-models.json").write_text(json.dumps({"models": TEMPLATES}))
    return ch


def _run(impl, ch, new_base):
    env = {k: v for k, v in os.environ.items() if k not in ("CODEX_HOME",)}
    env.update(CODEX_HOME=str(ch), CARHER_MIGRATE_TO=new_base, HOME=str(ch.parent), PATH="/usr/bin:/bin",
               CARHER_CODEX="none", CARHER_CODEX_SYS_PREFIXES=str(ch.parent / "nosys"))
    cmd = [shutil.which("node"), str(SRC / "carher_models_sync.js")] if impl == "js" else [shutil.which("python3"), str(SRC / "carher_models_sync.py")]
    return subprocess.run(cmd, env=env, capture_output=True, text=True, timeout=120)


@pytest.mark.parametrize("impl", ["js", "py"])
def test_sync_moves_old_base_when_new_reachable(tmp_path, gw, impl):
    ch = _home(tmp_path)
    _GW.hits.clear()
    r = _run(impl, ch, gw)
    assert r.returncode == 0, r.stdout + r.stderr
    t = (ch / "config.toml").read_text()
    assert OLD not in t and t.count(f'"{gw}"') == 2, t
    # 除了地址和同步本来就会补的 model_catalog_json 一行(及其后空行),其它逐行不变
    norm = lambda s: [l for l in s.splitlines() if l.strip() and not l.startswith("model_catalog_json")]
    assert norm(t) == norm(CFG.replace(OLD, gw)), t
    assert "/model/v1/models" in _GW.hits[0], "必须先用 key 打新地址 /models"
    assert "网关地址已换成新地址" in r.stdout
    shown = [m["slug"] for m in json.loads((ch / "carher-models.json").read_text())["models"] if m["visibility"] == "list"]
    assert "grok-4.7" in shown, "菜单要来自新地址拉到的列表"
    assert KEY not in r.stdout + r.stderr


@pytest.mark.parametrize("impl", ["js", "py"])
def test_sync_keeps_old_base_when_new_unreachable(tmp_path, impl):
    ch = _home(tmp_path)
